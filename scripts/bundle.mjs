// One self-contained file (server + dependencies) that runs with Node alone: bundle/sinequa-docs-mcp.mjs.
import { readFileSync } from "node:fs";
import { build } from "esbuild";

const { name, version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));

await build({
  entryPoints: ["src/cli.ts"],
  outfile: "bundle/sinequa-docs-mcp.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  minify: true,
  legalComments: "eof",
  banner: {
    js: [
      `// ${name} ${version} — generated by \`npm run bundle\` (esbuild): do not edit, rebuild from the source.`,
      "// Dependency licenses are at the end of the file.",
      // Bundled CommonJS dependencies call require(), which an ES module does not define.
      'import { createRequire } from "node:module"; const require = createRequire(import.meta.url);',
    ].join("\n"),
  },
  logLevel: "info",
});
